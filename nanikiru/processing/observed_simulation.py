"""Replay confirmed simulator observations, never full-state commands.

The visible delta is generated by the simulator projection, not an engine
permission. This vocabulary is separate from manually entered draw/discard.
"""

from copy import deepcopy
from dataclasses import replace

from ..models import PlayerInfo, TileRecord

KINDS = {"draw", "discard", "kan_declared", "pass", "response", "riichi_accepted",
         "chi", "pon", "open_kan", "closed_kan", "added_kan", "ended", "riichi_declared", "dora"}
FIELDS = {"players", "tiles", "groups", "riichi_sticks", "phase", "actor", "draw_context",
          "pending", "remaining_draws"}


def apply_observation(position, event):
    if event.kind.split("_",1)[-1] not in KINDS or set(event.data) != {"fact", "changes"}:
        raise ValueError("Invalid simulator observation event")
    changes = deepcopy(event.data["changes"])
    if not isinstance(changes, dict) or changes.keys() - FIELDS:
        raise ValueError("Unsupported observation delta")
    if "players" in changes:
        changes["players"] = tuple(PlayerInfo(**p) for p in changes["players"])
    if "tiles" in changes:
        changes["tiles"] = tuple(TileRecord(**t) for t in changes["tiles"])
    if isinstance(changes.get("pending"), dict):
        changes["pending"]["responses"] = {int(k): v for k, v in changes["pending"]["responses"].items()}
    return replace(deepcopy(position), **changes)
